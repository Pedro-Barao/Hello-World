DROP TABLE IF EXISTS ITEM_VENDA;
DROP TABLE IF EXISTS VENDA;
DROP TABLE IF EXISTS CLIENTE;
DROP TABLE IF EXISTS PROMOCAO;
DROP TABLE IF EXISTS LIVRO;
DROP TABLE IF EXISTS AUTOR;
DROP TABLE IF EXISTS EDITORA;
DROP TABLE IF EXISTS GENERO;

CREATE TABLE AUTOR (

    Id_Autor    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    Nome_Autor  VARCHAR2(40) NOT NULL,
    Email       VARCHAR2(60)

);

CREATE TABLE EDITORA (

    Id_Editora   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    Nome_Editora VARCHAR2(40) NOT NULL

);

CREATE TABLE GENERO (

    Id_Genero   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    Nome_Genero VARCHAR2(30) NOT NULL

);

CREATE TABLE CLIENTE (

    Id_Cliente   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    Nome_Cliente VARCHAR2(40) NOT NULL,
    Telefone     VARCHAR2(15)

);

CREATE TABLE LIVRO (

    Id_Livro        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    Titulo          VARCHAR2(50)  NOT NULL,
    Preco           DECIMAL(8, 2) NOT NULL,
    Ano_Publicacao  NUMBER(4),
    -- 1.2 --
    Estoque         NUMBER(5)     DEFAULT 0 NOT NULL,
    Id_Autor        NUMBER        NOT NULL,
    Id_Editora      NUMBER        NOT NULL,
    Id_Genero       NUMBER        NOT NULL,

    CONSTRAINT FK_Id_Autor   FOREIGN KEY (Id_Autor)   REFERENCES AUTOR(Id_Autor),
    CONSTRAINT FK_Id_Editora FOREIGN KEY (Id_Editora) REFERENCES EDITORA(Id_Editora),
    CONSTRAINT FK_Id_Genero  FOREIGN KEY (Id_Genero)  REFERENCES GENERO(Id_Genero)



);

CREATE TABLE VENDA (

    Id_Venda    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    Id_Cliente  NUMBER NOT NULL,
    Data_Venda  DATE   NOT NULL,

    CONSTRAINT FK_Id_Cliente_Venda FOREIGN KEY (Id_Cliente) REFERENCES CLIENTE(Id_Cliente)

);

CREATE TABLE ITEM_VENDA (

    Id_Livro       NUMBER        NOT NULL,
    Id_Venda       NUMBER        NOT NULL,
    Quantidade     NUMBER(3)     NOT NULL,
    Preco_Unitario DECIMAL(8, 2) NOT NULL,

    CONSTRAINT FK_Id_Livro_Item_Venda FOREIGN KEY (Id_Livro) REFERENCES LIVRO(Id_Livro),
    CONSTRAINT FK_Id_Venda            FOREIGN KEY (Id_Venda) REFERENCES VENDA(Id_Venda),
    CONSTRAINT PK_Id_Livro_Venda PRIMARY KEY (Id_Livro, Id_Venda)

);

